// Ředitelna → Přístupy (ostrý provoz): pozvat učitelku, registrace, blokace.
const T = require('./pomocnik');
module.exports = async (b) => {
  const mail = 'uc.' + Date.now().toString(36) + '@e2e.test';
  const r = await T.stranka(b);
  await T.prihlas(r, 'Ředitelna', T.ucet('reditelka.a'));
  T.over('ředitelka A se přihlásí', (await T.hash(r)) === '#reditel', await T.hash(r));
  await r.click('nav button:has-text("Přístupy")'); await r.waitForTimeout(1500);
  const seznam = await r.locator('section[aria-label="Přístupy"]').innerText();
  T.over('Přístupy: seznam ze serveru (učitelka A)', seznam.includes('Petra Horáková (test)'));
  T.over('Přístupy: nevidí zaměstnance školky B', !seznam.includes('Eva Učitelka (test)'));
  await r.click('button:has-text("+ Nový přístup")');
  await r.fill('#pr-jmeno', 'Klára E2E'); await r.fill('#pr-email', mail);
  await r.click('[role=dialog][aria-label="Nový přístup"] button:has-text("Vytvořit přístup")'); await r.waitForTimeout(800);
  T.over('Přístupy: učitelka bez třídy odmítnuta', /třídu/.test(await r.locator('[role=dialog] [role=alert]').textContent().catch(() => '')));
  await r.click('[role=dialog][aria-label="Nový přístup"] button:has-text("Sluníčka")');
  await r.click('[role=dialog][aria-label="Nový přístup"] button:has-text("Vytvořit přístup")'); await r.waitForTimeout(1500);
  const kod = (await r.locator('[role=dialog][aria-label="Heslo"] span').nth(3).textContent()).trim();
  T.over('Přístupy: kód pozvánky', /^[A-Z0-9]{4}-[A-Z0-9]{4}$/.test(kod), kod);
  await r.click('[role=dialog][aria-label="Heslo"] button:has-text("Hotovo")'); await r.waitForTimeout(1200);
  const u = await T.stranka(b, { width: 1194, height: 834 });
  await u.goto(T.WEB + '#prihlaseni'); await u.waitForTimeout(1200);
  await u.click('[aria-label="Kam se přihlásit"] button:has-text("Třída")');
  await u.click('button:has-text("Mám pozvánku")');
  await u.fill('#prihlaseni-email', mail); await u.fill('#prihlaseni-heslo', 'heslo-ucitelky-1'); await u.fill('#prihlaseni-kod', kod);
  await u.click('section[aria-label="Přihlášení"] >> button:has-text("Vytvořit")'); await u.waitForTimeout(3500);
  T.over('učitelka po registraci otevře tablet třídy', (await T.hash(u)) === '#trida', (await T.hash(u)) + ' ' + (await T.hlaska(u)));
  T.over('tablet: vidí děti své třídy (Ema)', (await u.locator('body').innerText()).includes('Ema'));
  T.over('tablet: nevidí děti z Berušek (Anna)', !(await u.locator('body').innerText()).includes('Anna'));
  await r.click('nav button:has-text("Přehled")').catch(() => {}); await r.waitForTimeout(300);
  await r.click('nav button:has-text("Přístupy")'); await r.waitForTimeout(1500);
  await r.locator('section[aria-label="Přístupy"] div[style*="grid-template-columns"]', { hasText: mail }).locator('button:has-text("Zablokovat")').click(); await r.waitForTimeout(1500);
  T.over('Přístupy: blokace uložena', T.sql(`select aktivni from uzivatele where email = '${mail}'`) === 'f');
  const u2 = await T.stranka(b, { width: 1194, height: 834 });
  await T.prihlas(u2, 'Třída', mail, 'heslo-ucitelky-1');
  T.over('blokovaná učitelka se nepřihlásí', /zablokovan/.test(await T.hlaska(u2)), await T.hlaska(u2));
  T.over('bez chyb v konzoli', !r.chyby.length && !u.chyby.length, r.chyby.concat(u.chyby).join(' | '));
  return T.konec('pristupy');
};
